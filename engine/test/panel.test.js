// Static consistency checks for the CEP panel. These run in plain Node and
// catch the class of bug that made "Align" silently do nothing: a script that
// never registered, or a DOM id the JS reaches for that no longer exists.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_PARAMS } from '../src/align.js';

const PANEL = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'cep');
const html = readFileSync(join(PANEL, 'index.html'), 'utf8');
const ids = new Set([...html.matchAll(/id="([^"]+)"/g)].map((m) => m[1]));

test('every script index.html loads exists on disk', () => {
  const scripts = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
  assert.ok(scripts.length >= 4, 'expected the panel to load its js modules');
  for (const rel of scripts) {
    assert.ok(existsSync(join(PANEL, rel)), `missing script ${rel}`);
  }
});

test('the version shown in the footer matches the manifest', () => {
  const manifest = readFileSync(join(PANEL, 'CSXS/manifest.xml'), 'utf8');
  const mv = manifest.match(/ExtensionBundleVersion="([^"]+)"/);
  assert.ok(mv, 'manifest has no ExtensionBundleVersion');
  const fv = html.match(/id="version">Unphased v([\d.]+)</);
  assert.ok(fv, 'footer has no version string');
  // footer carries major.minor; the manifest is major.minor.patch
  assert.ok(
    mv[1].startsWith(fv[1]),
    `footer says v${fv[1]} but the manifest says ${mv[1]}`
  );
});

test('every font the stylesheet references is bundled', () => {
  // Fonts are bundled deliberately so the panel renders identically offline;
  // a missing file silently falls back to a system font.
  const css = readFileSync(join(PANEL, 'css/panel.css'), 'utf8');
  const urls = [...css.matchAll(/url\('([^']+)'\)/g)].map((m) => m[1]);
  assert.ok(urls.length > 0, 'expected bundled @font-face sources');
  for (const rel of urls) {
    const p = join(PANEL, 'css', rel.replace(/\//g, '\\'));
    assert.ok(existsSync(p), `missing font ${rel}`);
  }
});

test('every CSS class the panel JS assigns exists in the stylesheet', () => {
  const css = readFileSync(join(PANEL, 'css/panel.css'), 'utf8');
  const main = readFileSync(join(PANEL, 'js/main.js'), 'utf8');
  const missing = [];
  // classes assigned via className = '...' or class="..." in template strings
  for (const m of main.matchAll(/className = '([^']+)'/g)) {
    for (const cls of m[1].split(/\s+/)) {
      if (!cls || cls.startsWith('log-')) continue; // log-* are generated by type
      if (!css.includes('.' + cls)) missing.push(cls);
    }
  }
  for (const m of main.matchAll(/class="([^"'{}]+)"/g)) {
    for (const cls of m[1].split(/\s+/)) {
      if (!cls) continue;
      if (!css.includes('.' + cls)) missing.push(cls);
    }
  }
  assert.deepEqual([...new Set(missing)], [], 'panel JS uses classes with no styles');
});

test('every DOM id the panel JS uses exists in index.html', () => {
  const missing = [];
  for (const file of ['js/main.js', 'js/bridge.js', 'js/jobRunner.js']) {
    const src = readFileSync(join(PANEL, file), 'utf8');
    for (const m of src.matchAll(/getElementById\((['"])([^'"]+)\1\)/g)) {
      if (!ids.has(m[2])) missing.push(`${file}: #${m[2]}`);
    }
    for (const m of src.matchAll(/\$\((['"])([^'"]+)\1\)/g)) {
      if (!ids.has(m[2])) missing.push(`${file}: $('${m[2]}')`);
    }
  }
  assert.deepEqual(missing, [], `panel JS references ids that do not exist: ${missing.join(', ')}`);
});

test('pairing.js exports to the window even when a CommonJS module object exists', () => {
  // CEP with --enable-nodejs injects `module` into the page scope. An
  // either/or UMD wrapper would silently skip the global assignment, which is
  // exactly what stopped the Align button working.
  const src = readFileSync(join(PANEL, 'js/pairing.js'), 'utf8');
  const root = { };
  const fakeModule = { exports: {} };
  // eslint-disable-next-line no-new-func
  new Function('module', 'self', src)(fakeModule, root);
  assert.ok(fakeModule.exports.buildPairs, 'should populate module.exports');
  assert.ok(root.UnphasedPairing && root.UnphasedPairing.buildPairs,
    'should ALSO populate the global when a module object is present');
});

function paramsSentByPanel() {
  const main = readFileSync(join(PANEL, 'js/main.js'), 'utf8');
  const start = main.indexOf('function readParams');
  assert.ok(start > 0, 'readParams not found');
  // The next function definition marks readParams' own closing brace —
  // resilient to whatever follows it, unlike pinning to a specific name.
  const end = main.indexOf('function ', start + 'function readParams'.length);
  assert.ok(end > start, 'expected another function to follow readParams');
  return [...main.slice(start, end).matchAll(/^\s{6}(\w+):/gm)].map((m) => m[1]);
}

test('params the panel sends are all understood by the engine', () => {
  const sent = paramsSentByPanel();
  assert.ok(sent.length >= 2, 'expected readParams to send some params');
  for (const key of sent) {
    assert.ok(key in DEFAULT_PARAMS, `panel sends "${key}" which the engine ignores`);
  }
});

test('the panel does not pin the search window', () => {
  // maxShiftMs is derived per clip by widening on evidence. A UI that pins it
  // reintroduces the failure this replaced: too narrow a window returns a
  // confident wrong answer rather than an error.
  assert.ok(!paramsSentByPanel().includes('maxShiftMs'),
    'the panel should leave maxShiftMs on auto');
});

test('the selection payload the panel reads is the one the host sends', () => {
  // A host/panel field mismatch here is invisible: the panel just reports that
  // nothing is selected, which is indistinguishable from a real empty selection.
  const jsx = readFileSync(join(PANEL, 'jsx/host.jsx'), 'utf8');
  const main = readFileSync(join(PANEL, 'js/main.js'), 'utf8');
  for (const field of ['method', 'reportedByHost', 'matchedOnAudioTracks']) {
    assert.ok(jsx.includes(field), `host.jsx does not send selection.${field}`);
    assert.ok(main.includes(field), `main.js does not read selection.${field}`);
  }
  // Selection must be resolved for the sequence, not asked of each clip: per-clip
  // isSelected() is absent or stale on some builds.
  assert.ok(jsx.includes('getSelection()'), 'host.jsx should read the sequence selection');
});

test('rendered audio is not written into the job temp dir', () => {
  // The rendered WAVs are project media: Premiere references them for the life
  // of the project. Writing them under os.tmpdir() means Disk Cleanup or a
  // reboot takes them and the timeline goes offline weeks later.
  const main = readFileSync(join(PANEL, 'js/main.js'), 'utf8');
  const runner = readFileSync(join(PANEL, 'js/jobRunner.js'), 'utf8');
  assert.ok(!/outputPath:\s*jobDir/.test(main),
    'outputPath should resolve against the render dir, not the job temp dir');
  assert.ok(/resolveRenderDir/.test(main) && /resolveRenderDir/.test(runner),
    'the panel should resolve a render dir before building the job');
  // …and the project folder must be preferred over temp.
  const fn = runner.slice(runner.indexOf('function resolveRenderDir'));
  assert.ok(fn.indexOf('projectPath') < fn.indexOf('tmpdir'),
    'temp should only be the fallback after the project folder');
});

test('the host jsx defines every AA_ function the panel calls', () => {
  const jsx = readFileSync(join(PANEL, 'jsx/host.jsx'), 'utf8');
  const defined = new Set([...jsx.matchAll(/function (AA_\w+)/g)].map((m) => m[1]));
  const called = new Set();
  for (const file of ['js/main.js', 'js/jobRunner.js']) {
    const src = readFileSync(join(PANEL, file), 'utf8');
    for (const m of src.matchAll(/call\((['"])(AA_\w+)\1/g)) called.add(m[2]);
  }
  assert.ok(called.size >= 3, 'expected the panel to call several host functions');
  for (const fn of called) {
    assert.ok(defined.has(fn), `panel calls ${fn} but host.jsx does not define it`);
  }
});
