#!/usr/bin/env node
// build-engine.js — regenerate uxp/js/engine/ from the shared engine source.
//
// The DSP lives once, in ../engine/src, as ES modules that `node --test` runs
// directly. UXP's module loader is CommonJS, so this script rewrites the pure
// modules into js/engine/*.js. The rewrite is deliberately dumb — the engine
// only ever uses two syntactic forms:
//
//     import { a, b } from './x.js';   ->   const { a, b } = require("./x.js");
//     export function f(...)           ->   function f(...)   (+ module.exports)
//     export const K = ...             ->   const K = ...     (+ module.exports)
//
// Anything else (default exports, `export {}` lists, star imports, a `node:`
// import sneaking into a module we claim is pure) is a hard error rather than a
// silent mistranslation.
//
// js/pairing.js is NOT generated — it is a hand-maintained UMD panel module
// that the engine test suite requires directly.
//
// Generated files are committed so the plugin folder is loadable as-is. Run
//   node scripts/build-engine.js --check
// (which `npm run lint` does) to fail the build when they drift from source.
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const REPO = path.resolve(ROOT, "..");
const SRC = path.join(REPO, "engine", "src");
const OUT = path.join(ROOT, "js", "engine");

// The pure DSP. Deliberately excludes:
//   decode.js   — spawns ffmpeg (replaced by js/audio.js + the native addon)
//   progress.js — writes NDJSON to stdout (replaced by runner.js callbacks)
//   wavFile.js  — node:fs wrappers (UXP reads/writes through its own fs)
const MODULES = [
    "align.js", "coarse.js", "coherence.js", "decimate.js", "fft.js",
    "gccPhat.js", "job.js", "lattice.js", "pathSolver.js", "phaseAlign.js",
    "polarity.js", "varyDelay.js", "wav.js"
];

const BANNER = (from) =>
    `// GENERATED by uxp/scripts/build-engine.js from ${from} — do not edit.\n` +
    `// Change the shared engine source and re-run \`npm run build:engine\`.\n\n`;

function transpile(file) {
    const src = fs.readFileSync(path.join(SRC, file), "utf8");
    const exported = [];
    const out = src.split("\n").map((line, i) => {
        const where = `${file}:${i + 1}`;

        if (/^\s*import\b/.test(line)) {
            const named = /^import\s+\{([^}]+)\}\s+from\s+'([^']+)';?\s*$/.exec(line);
            if (!named) throw new Error(`${where}: unsupported import form — ${line.trim()}`);
            const [, names, from] = named;
            if (!from.startsWith("./")) {
                throw new Error(`${where}: '${from}' is not a relative engine import — ` +
                    `this module is not pure and must not be bundled for UXP`);
            }
            return `const {${names}} = require("${from}");`;
        }

        if (/^\s*export\b/.test(line)) {
            const decl = /^export\s+(function|const|let|class)\s+([A-Za-z_$][\w$]*)/.exec(line);
            if (!decl) throw new Error(`${where}: unsupported export form — ${line.trim()}`);
            exported.push(decl[2]);
            return line.replace(/^export\s+/, "");
        }

        return line;
    }).join("\n");

    if (!exported.length) throw new Error(`${file}: nothing exported — check the transpiler`);
    return BANNER(`engine/src/${file}`) + out.replace(/\s*$/, "\n") +
        `\nmodule.exports = { ${exported.join(", ")} };\n`;
}

const artifacts = new Map();
for (const m of MODULES) artifacts.set(path.join(OUT, m), transpile(m));

const check = process.argv.includes("--check");
let drifted = 0;
fs.mkdirSync(OUT, { recursive: true });
for (const [dest, content] of artifacts) {
    const rel = path.relative(ROOT, dest).replace(/\\/g, "/");
    const current = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
    if (current === content) continue;
    if (check) {
        console.error(`build-engine: ${rel} is stale — run \`npm run build:engine\``);
        drifted++;
    } else {
        fs.writeFileSync(dest, content);
        console.log(`build-engine: wrote ${rel}`);
    }
}

if (check) {
    if (drifted) process.exit(1);
    console.log(`build-engine: ${artifacts.size} generated files match the shared source ✓`);
} else if (!drifted) {
    console.log(`build-engine: ${artifacts.size} files up to date`);
}
